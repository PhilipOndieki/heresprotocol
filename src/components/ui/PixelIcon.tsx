interface PixelIconProps {
  variant: PixelIconVariant
  size?: number
  color?: string
  className?: string
  dotSize?: number
  gap?: number
}

export function PixelIcon({
  variant,
  size = 48,
  color = 'var(--color-violet)',
  className,
  dotSize,
  gap,
}: PixelIconProps) {
  const grid = GRIDS[variant]
  const rows = grid.length
  const cols = (grid[0] ?? []).length
  const resolvedDot = dotSize ?? Math.max(2, Math.floor(size / 20))
  const resolvedGap = gap ?? Math.max(1, Math.floor(size / 36))
  const totalW = cols * (resolvedDot + resolvedGap) - resolvedGap
  const totalH = rows * (resolvedDot + resolvedGap) - resolvedGap

  return (
    <svg
      width={totalW}
      height={totalH}
      viewBox={`0 0 ${totalW} ${totalH}`}
      aria-hidden="true"
      className={cn('block shrink-0', className)}
    >
      {grid.flatMap((row, r) =>
        row.map((cell, c) =>
          cell ? (
            <rect
              key={`${r}-${c}`}
              x={c * (resolvedDot + resolvedGap)}
              y={r * (resolvedDot + resolvedGap)}
              width={resolvedDot}
              height={resolvedDot}
              fill={color}
            />
          ) : null
        )
      )}
    </svg>
  )
}
